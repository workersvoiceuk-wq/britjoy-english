/** Module text in the interface language: Spanish from the outline, English from MODULE_EN. */
export function moduleText(m: { id: string; unit: string; title: string; lessons: Array<{ title: string; objective?: string }> }, ui: Ui) {
  const n = Number(m.id.slice(0, 2));
  if (ui === 'es') return { unit: m.unit, title: m.title, lesson: m.lessons[0]?.title ?? '', objective: m.lessons[0]?.objective ?? '' };
  const en = MODULE_EN[m.id];
  return { unit: `${T.en.module} ${n}`, title: en?.title ?? m.title, lesson: en?.lesson ?? m.lessons[0]?.title ?? '', objective: en?.objective ?? m.lessons[0]?.objective ?? '' };
}
