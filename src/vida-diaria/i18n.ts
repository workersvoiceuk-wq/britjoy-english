  '01-presentaciones': { title: 'Introductions', lesson: 'Hello, I am Ana', objective: 'Talk about yourself, your country, your family and your interests.' },
  '02-compras': { title: 'Shopping', lesson: 'At the supermarket', objective: 'Ask prices, find products and ask for a refund.' },
  '03-transporte': { title: 'Transport', lesson: 'How do I get to…?', objective: 'Ask for directions, buy tickets and understand announcements.' },
  '04-vivienda': { title: 'Housing', lesson: 'The boiler is not working', objective: 'Look for a room, talk to the landlord and report a fault.' },
  '05-salud': { title: 'Health', lesson: 'Lucía has a fever', objective: 'Book a GP appointment, explain symptoms and speak at the pharmacy.' },
  '06-empleo': { title: 'Job hunting', lesson: "Ana's interview", objective: 'Understand job ads, prepare a CV and answer in interviews.' },
  '07-trabajo': { title: 'English at work', lesson: 'First day in the kitchen', objective: 'Understand instructions, explain tasks and ask for materials.' },
  '08-llamadas': { title: 'Calls and e-mails', lesson: 'Leave a message after the tone', objective: 'Leave messages, confirm appointments and write requests.' },
  '09-colegio': { title: 'School and family', lesson: 'The meeting with the teacher', objective: 'Talk to teachers and understand school communications.' },
  '10-servicios': { title: 'Public services', lesson: 'At the library and the council', objective: 'Ask for information, fill in forms and request help.' },
